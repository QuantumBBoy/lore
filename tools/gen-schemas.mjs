#!/usr/bin/env node
// Embed the JSON Schemas from spec/schemas into lore-core, so the library validates against the
// published schemas without reading files at runtime. Run after changing a schema:
//   node tools/gen-schemas.mjs
// A test fails when lore-core/src/schemas.generated.mjs is out of date.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const OUT = join(ROOT, 'lore-core', 'src', 'schemas.generated.mjs');

export function generateSchemasModule() {
  const dir = join(ROOT, 'spec', 'schemas');
  const schemas = readdirSync(dir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
  const body = schemas.map((s) => `  ${JSON.stringify(s.$id)}: ${JSON.stringify(s)},`).join('\n');
  return `// Generated by tools/gen-schemas.mjs from spec/schemas. Do not edit.\n\nexport const SCHEMAS = {\n${body}\n};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, generateSchemasModule());
  console.log(`Wrote ${OUT}`);
}
