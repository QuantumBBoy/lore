#!/usr/bin/env node
// Embed the JSON Schemas of every spec version into lore-core (the current ones in spec/schemas,
// earlier ones frozen in spec/<version>/schemas), so the library validates a folder against the
// schemas of the version it declares, without reading files at runtime. Run after changing a schema:
//   node tools/gen-schemas.mjs
// A test fails when lore-core/src/schemas.generated.mjs is out of date.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const OUT = join(ROOT, 'lore-core', 'src', 'schemas.generated.mjs');

/** Schema folders: frozen earlier versions first, then the current one. */
export function schemaDirs() {
  const spec = join(ROOT, 'spec');
  const frozen = readdirSync(spec, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^\d+\.\d+$/.test(d.name))
    .map((d) => d.name)
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  return [...frozen.map((v) => join(spec, v, 'schemas')), join(spec, 'schemas')];
}

export function generateSchemasModule() {
  const schemas = schemaDirs().flatMap((dir) =>
    readdirSync(dir)
      .filter((f) => f.endsWith('.schema.json'))
      .sort()
      .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8'))),
  );
  const body = schemas.map((s) => `  ${JSON.stringify(s.$id)}: ${JSON.stringify(s)},`).join('\n');
  return `// Generated by tools/gen-schemas.mjs from spec/schemas and spec/<version>/schemas. Do not edit.\n\nexport const SCHEMAS = {\n${body}\n};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, generateSchemasModule());
  console.log(`Wrote ${OUT}`);
}
